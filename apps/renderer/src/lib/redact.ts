/**
 * التمويه قبل الإرسال — بلاغات الدعم تُنشر على مستودع عام.
 *
 * يُخفى ما يكشف مال الشركة وأطرافها: المبالغ، وأرقام الحسابات بعد بادئتها (٢١١/٢١٢/٢١٦
 * تبقى لأنها تقول نوع الحساب وهو ما يحتاجه من يُصلح الخلل، والباقي هوية طرف بعينه).
 * التواريخ لا تُمسّ — كثير من الأخطاء متعلق بها، ولا تكشف شيئاً بمفردها.
 *
 * المستخدم يرى النص بعد التمويه قبل الإرسال، فلا يُرسل شيء لم يره.
 */
const AR_DIGITS = '٠١٢٣٤٥٦٧٨٩';
const toLatin = (s: string) => s.replace(/[٠-٩]/g, (d) => String(AR_DIGITS.indexOf(d)));

/** مبلغ: آلاف بفواصل، أو كسر عشري بخانتين — بالأرقام اللاتينية أو العربية. */
const MONEY_RE = /\(?-?\d{1,3}(?:[,٬]\d{3})+(?:[.٫]\d{1,2})?\)?|\(?-?\d+[.٫]\d{2}\)?/g;
/** رمز حساب أو أي سلسلة أرقام طويلة: تبقى أول ثلاثة أرقام. */
const CODE_RE = /\b(\d{3})\d{2,}\b/g;

export function redactText(s: string): string {
  return toLatin(s)
    .replace(/\d{4}-\d{2}-\d{2}/g, (d) => d.replace(/-/g, '‐'))   // حماية التواريخ مؤقتاً
    .replace(MONEY_RE, '•••')
    .replace(CODE_RE, '$1•••')
    .replace(/‐/g, '-');
}

/** المسار الحالي بلا رقم الحساب الكامل (‎#/suppliers/2110808 ← ‎#/suppliers/211•••). */
export function redactRoute(hash: string): string {
  return hash.replace(CODE_RE, '$1•••');
}
