# -*- coding: utf-8 -*-
"""تطبيع عربي للمقارنة — لا للتخزين ولا للعرض.

المستخدم يكتب الاسم كما يراه صحيحاً إملائياً (بيت الآباء، الهضبة)، بينما نظامه
المحاسبي القديم صدَّر نفس الاسم بإملاء آخر (بيت الاباء، الهضبه) — نفس الكيان،
حرفان مختلفان بصرياً بالكاد. أي مقارنة نصية حرفية بين الاثنين (بحث، تصفية
بمشروع، تحقّق من تكرار مشروع عند الإدخال) تفشل بصمت: النتائج تختفي، والمشروع
يتكرر باسمين. هذه الدالة نقطة تطبيع واحدة يُعاد استخدامها في كل تلك المقارنات
بدل أن تتكرر شرطاً مختلفاً قليلاً في كل ملف.

القاعدة الصارمة: النتيجة من normalize_ar() تُستخدم للمقارنة فقط. لا تُخزَّن في
قاعدة البيانات ولا تُعرض للمستخدم — هو يجب أن يرى الاسم كما كتبه نظامه المحاسبي
بالضبط، وإلا فقد الثقة بأن الشاشة تعكس ملفاته الأصلية بلا تحريف.

مبني على نفس ملاحظة `_norm` في app/ingest/pdf_statement.py (الياء الفارسية
والألف المقصورة توحَّدان لأن PDF يُخرجهما أحياناً حرفاً مختلفاً عن المكتوب)،
ويوسّعها لتغطية كل تنويعات الإملاء العربي الشائعة في أسماء الموردين والمقاولين
والمشاريع: الهمزات، التاء المربوطة، الألف المقصورة، الحروف الفارسية، التطويل،
والتشكيل.
"""
import re
import unicodedata

#: التشكيل والحركات — فتحة، ضمة، كسرة، سكون، شدة، تنوين، مدّة... إلخ.
_TASHKEEL = re.compile(
    '[ؐ-ًؚ-ٰٟۖ-ۜ۟-۪ۨ-ۭ]')

#: التطويل (الكشيدة) — يُدرج للتزيين البصري فقط ولا يغيّر معنى الكلمة.
_TATWEEL = 'ـ'

#: كل صور الألف (مع الهمزة فوق/تحت، بالمدة) → ألف عادية.
_ALEF = re.compile('[إأآٱا]')

#: الياء الفارسية والألف المقصورة → ياء عادية (نفس ملاحظة pdf_statement._norm).
_YEH = re.compile('[يیى]')

#: الكاف الفارسية → كاف عربية.
_KAF = re.compile('[کﻙﻚ]')

#: التاء المربوطة وهاء الفارسية (heh goal) → هاء عادية — «شركة»/«شركه» نفس الكلمة.
_HEH = re.compile('[ةھه]')


def normalize_ar(s: str) -> str:
    """يُرجع صورة الاسم المُوحَّدة للمقارنة فقط — لا تُخزَّن ولا تُعرض أبداً.

    فارغ أو None يُرجعان ''، حتى لا تنكسر مقارنة needle in haystack على مدخل غائب.
    """
    if not s:
        return ''
    s = unicodedata.normalize('NFKC', s)
    s = _TASHKEEL.sub('', s)
    s = s.replace(_TATWEEL, '')
    s = _ALEF.sub('ا', s)
    s = _YEH.sub('ي', s)
    s = _KAF.sub('ك', s)
    s = _HEH.sub('ه', s)
    # فراغات متعددة (أو ناتجة عن حذف التشكيل بين حرفين متلاصقين أصلاً) → فراغ واحد.
    s = re.sub(r'\s+', ' ', s).strip()
    return s


def contains_ar(haystack: str, needle: str) -> bool:
    """هل يحوي haystack كلمة needle، بصرف النظر عن اختلافات الإملاء أعلاه؟

    needle فارغ يُطابق دائماً (سلوك «لا تصفية» المتوقع في كل نقاط الاستدعاء).
    """
    if not needle or not needle.strip():
        return True
    return normalize_ar(needle) in normalize_ar(haystack)


def same_ar(a: str, b: str) -> bool:
    """هل a و b نفس الاسم إملائياً بعد التطبيع؟ — لتجميع مشروعين بنفس الهوية."""
    return normalize_ar(a) == normalize_ar(b)
